import json

def sql_escape(s):
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"

def main():
    with open('data/workplan_dataset.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    project = data['project']
    milestones = data['milestones']
    tasks = data['tasks']
    assignees = data['assignees']

    sql_lines = []
    sql_lines.append("-- ====================================================================")
    sql_lines.append("-- Supabase PostgreSQL Schema & Work Plan Seed Data (RM-Retail POS V2.0)")
    sql_lines.append("-- Architecture: Vercel Serverless + Supabase (PostgreSQL)")
    sql_lines.append("-- Generated from: Project Detail Work Plan RM-Retail POS V2.0_20261015.xlsx")
    sql_lines.append("-- ====================================================================")
    sql_lines.append("")

    # Drop / Create Tables
    sql_lines.append("-- 1. Create Projects Table")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.projects (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  name VARCHAR(255) NOT NULL,")
    sql_lines.append("  description TEXT DEFAULT NULL,")
    sql_lines.append("  assignee VARCHAR(255) DEFAULT NULL,")
    sql_lines.append("  status VARCHAR(50) DEFAULT 'Active',")
    sql_lines.append("  wbs VARCHAR(50) DEFAULT '0',")
    sql_lines.append("  percent_complete NUMERIC(5,2) DEFAULT 0.00,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,")
    sql_lines.append("  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    sql_lines.append("-- 2. Create Stages Table (Milestones)")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.stages (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  project_id BIGINT NOT NULL REFERENCES public.projects (id) ON DELETE CASCADE,")
    sql_lines.append("  wbs VARCHAR(50) DEFAULT NULL,")
    sql_lines.append("  title VARCHAR(255) NOT NULL,")
    sql_lines.append("  start_date DATE NOT NULL,")
    sql_lines.append("  end_date DATE NOT NULL,")
    sql_lines.append("  color VARCHAR(7) DEFAULT '#7b879a',")
    sql_lines.append("  sort_order INT DEFAULT 0,")
    sql_lines.append("  assignee VARCHAR(255) DEFAULT NULL,")
    sql_lines.append("  duration VARCHAR(50) DEFAULT NULL,")
    sql_lines.append("  weight_pct INT DEFAULT 0,")
    sql_lines.append("  percent_complete NUMERIC(5,2) DEFAULT 0.00,")
    sql_lines.append("  percent_work_complete NUMERIC(5,2) DEFAULT 0.00,")
    sql_lines.append("  status VARCHAR(50) DEFAULT 'Not Started',")
    sql_lines.append("  stuck_reason TEXT DEFAULT NULL,")
    sql_lines.append("  is_completed SMALLINT DEFAULT 0,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,")
    sql_lines.append("  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    sql_lines.append("-- 3. Create Tasks Table (WBS Level 2, 3, 4)")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.tasks (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  stage_id BIGINT NOT NULL REFERENCES public.stages (id) ON DELETE CASCADE,")
    sql_lines.append("  wbs VARCHAR(50) DEFAULT NULL,")
    sql_lines.append("  title VARCHAR(255) NOT NULL,")
    sql_lines.append("  level INT DEFAULT 2,")
    sql_lines.append("  parent_wbs VARCHAR(50) DEFAULT NULL,")
    sql_lines.append("  start_date DATE NOT NULL,")
    sql_lines.append("  end_date DATE NOT NULL,")
    sql_lines.append("  duration VARCHAR(50) DEFAULT NULL,")
    sql_lines.append("  color VARCHAR(7) DEFAULT '#9fc7ff',")
    sql_lines.append("  lane INT DEFAULT 1,")
    sql_lines.append("  assignee VARCHAR(255) DEFAULT NULL,")
    sql_lines.append("  sort_order INT DEFAULT 0,")
    sql_lines.append("  percent_complete NUMERIC(5,2) DEFAULT 0.00,")
    sql_lines.append("  percent_work_complete NUMERIC(5,2) DEFAULT 0.00,")
    sql_lines.append("  status VARCHAR(50) DEFAULT 'Not Started',")
    sql_lines.append("  actual_start DATE DEFAULT NULL,")
    sql_lines.append("  actual_finish DATE DEFAULT NULL,")
    sql_lines.append("  stuck_reason TEXT DEFAULT NULL,")
    sql_lines.append("  remark TEXT DEFAULT NULL,")
    sql_lines.append("  is_completed SMALLINT DEFAULT 0,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,")
    sql_lines.append("  updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    sql_lines.append("-- 4. Create Assignees Table")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.assignees (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  name VARCHAR(255) NOT NULL UNIQUE,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    sql_lines.append("-- 5. Create Colors Table")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.colors (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  name VARCHAR(100) NOT NULL,")
    sql_lines.append("  color_code VARCHAR(7) NOT NULL UNIQUE,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    sql_lines.append("-- 6. Create Users Table (Supports local admin & Google OAuth account mapping)")
    sql_lines.append("CREATE TABLE IF NOT EXISTS public.users (")
    sql_lines.append("  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,")
    sql_lines.append("  username VARCHAR(100) NOT NULL UNIQUE,")
    sql_lines.append("  password VARCHAR(255) DEFAULT NULL,")
    sql_lines.append("  display_name VARCHAR(150) NOT NULL,")
    sql_lines.append("  email VARCHAR(255) DEFAULT NULL UNIQUE,")
    sql_lines.append("  google_id VARCHAR(255) DEFAULT NULL,")
    sql_lines.append("  avatar_url TEXT DEFAULT NULL,")
    sql_lines.append("  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP")
    sql_lines.append(");")
    sql_lines.append("")

    # Indexes
    sql_lines.append("-- Indexes for high-performance querying")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_stages_project_id ON public.stages(project_id);")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_tasks_stage_id ON public.tasks(stage_id);")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_stages_sort ON public.stages(sort_order, start_date);")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_tasks_sort ON public.tasks(sort_order, start_date);")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_tasks_wbs ON public.tasks(wbs);")
    sql_lines.append("CREATE INDEX IF NOT EXISTS idx_tasks_status ON public.tasks(status);")
    sql_lines.append("")

    # RLS
    sql_lines.append("-- ====================================================================")
    sql_lines.append("-- Row Level Security (RLS) Configuration")
    sql_lines.append("-- ====================================================================")
    sql_lines.append("ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("ALTER TABLE public.stages ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("ALTER TABLE public.assignees ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("ALTER TABLE public.colors ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;")
    sql_lines.append("")
    sql_lines.append("DROP POLICY IF EXISTS \"Public can read projects\" ON public.projects;")
    sql_lines.append("CREATE POLICY \"Public can read projects\" ON public.projects FOR SELECT USING (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Public can read stages\" ON public.stages;")
    sql_lines.append("CREATE POLICY \"Public can read stages\" ON public.stages FOR SELECT USING (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Public can read tasks\" ON public.tasks;")
    sql_lines.append("CREATE POLICY \"Public can read tasks\" ON public.tasks FOR SELECT USING (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Public can read assignees\" ON public.assignees;")
    sql_lines.append("CREATE POLICY \"Public can read assignees\" ON public.assignees FOR SELECT USING (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Public can read colors\" ON public.colors;")
    sql_lines.append("CREATE POLICY \"Public can read colors\" ON public.colors FOR SELECT USING (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on projects\" ON public.projects;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on projects\" ON public.projects FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on stages\" ON public.stages;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on stages\" ON public.stages FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on tasks\" ON public.tasks;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on tasks\" ON public.tasks FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on assignees\" ON public.assignees;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on assignees\" ON public.assignees FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on colors\" ON public.colors;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on colors\" ON public.colors FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("DROP POLICY IF EXISTS \"Enable all access for service role on users\" ON public.users;")
    sql_lines.append("CREATE POLICY \"Enable all access for service role on users\" ON public.users FOR ALL USING (true) WITH CHECK (true);")
    sql_lines.append("")

    # Clean existing data
    sql_lines.append("-- ====================================================================")
    sql_lines.append("-- Wipe Old Data and Seed New Work Plan (RM-Retail POS V2.0)")
    sql_lines.append("-- ====================================================================")
    sql_lines.append("TRUNCATE TABLE public.tasks, public.stages, public.projects, public.assignees, public.colors RESTART IDENTITY CASCADE;")
    sql_lines.append("")

    # Seed Admin User
    sql_lines.append("-- 1. Default Admin User (username: admin / password: admin123)")
    sql_lines.append("INSERT INTO public.users (id, username, password, display_name) VALUES")
    sql_lines.append("(1, 'admin', '$2a$10$3sRtPd1ORu1lwTm4UTW0w.FZQycJvTu0mf4I0JjU7.S2ocOggzL5i', 'System Administrator')")
    sql_lines.append("ON CONFLICT (username) DO NOTHING;")
    sql_lines.append("")

    # Seed Colors
    sql_lines.append("-- 2. Project Status Colors")
    sql_lines.append("INSERT INTO public.colors (name, color_code) VALUES")
    sql_lines.append("('Complete / Green', '#77c56b'),")
    sql_lines.append("('On Schedule / Blue', '#9fc7ff'),")
    sql_lines.append("('Late / Red', '#dc3d78'),")
    sql_lines.append("('Not Started / Slate', '#7b879a')")
    sql_lines.append("ON CONFLICT (color_code) DO NOTHING;")
    sql_lines.append("")

    # Seed Assignees
    sql_lines.append("-- 3. Project Assignees (Resources from Excel)")
    assignee_vals = [f"({sql_escape(a)})" for a in assignees]
    sql_lines.append("INSERT INTO public.assignees (name) VALUES")
    sql_lines.append(",\n".join(assignee_vals))
    sql_lines.append("ON CONFLICT (name) DO NOTHING;")
    sql_lines.append("")

    # Seed Project
    sql_lines.append("-- 4. Root Project: RM-Retail POS Project (JIFFY POS)")
    sql_lines.append("INSERT INTO public.projects (id, name, description, assignee, status, wbs, percent_complete) VALUES")
    sql_lines.append(f"({project['id']}, {sql_escape(project['name'])}, {sql_escape(project['description'])}, {sql_escape(project['assignee'])}, {sql_escape(project['status'])}, {sql_escape(project['wbs'])}, {project['percent_complete']});")
    sql_lines.append("")

    # Seed Stages
    sql_lines.append("-- 5. Major Milestones (Stages)")
    stage_rows = []
    for m in milestones:
        stage_rows.append(f"({m['id']}, {m['project_id']}, {sql_escape(m['wbs'])}, {sql_escape(m['title'])}, {sql_escape(m['start_date'])}, {sql_escape(m['end_date'])}, {sql_escape(m['color'])}, {m['sort_order']}, {sql_escape(m['assignee'])}, {sql_escape(m['duration'])}, {m['weight_pct']}, {m['percent_complete']}, {m['percent_work_complete']}, {sql_escape(m['status'])}, {m['is_completed']})")

    sql_lines.append("INSERT INTO public.stages (id, project_id, wbs, title, start_date, end_date, color, sort_order, assignee, duration, weight_pct, percent_complete, percent_work_complete, status, is_completed) VALUES")
    sql_lines.append(",\n".join(stage_rows) + ";")
    sql_lines.append("")

    # Seed Tasks in Batches
    sql_lines.append(f"-- 6. Work Plan Tasks ({len(tasks)} items)")
    batch_size = 50
    for i in range(0, len(tasks), batch_size):
        batch = tasks[i:i+batch_size]
        task_rows = []
        for t in batch:
            act_start = sql_escape(t['actual_start'])
            act_finish = sql_escape(t['actual_finish'])
            stuck = sql_escape(t['stuck_reason'])
            rem = sql_escape(t['remark'])
            task_rows.append(f"({t['id']}, {t['stage_id']}, {sql_escape(t['wbs'])}, {sql_escape(t['title'])}, {t['level']}, {sql_escape(t['parent_wbs'])}, {sql_escape(t['start_date'])}, {sql_escape(t['end_date'])}, {sql_escape(t['duration'])}, {sql_escape(t['color'])}, {t['lane']}, {sql_escape(t['assignee'])}, {t['sort_order']}, {t['percent_complete']}, {t['percent_work_complete']}, {sql_escape(t['status'])}, {act_start}, {act_finish}, {stuck}, {rem}, {t['is_completed']})")
        
        sql_lines.append("INSERT INTO public.tasks (id, stage_id, wbs, title, level, parent_wbs, start_date, end_date, duration, color, lane, assignee, sort_order, percent_complete, percent_work_complete, status, actual_start, actual_finish, stuck_reason, remark, is_completed) VALUES")
        sql_lines.append(",\n".join(task_rows) + ";")
        sql_lines.append("")

    # Reset sequences
    sql_lines.append("-- Reset serial sequences to avoid ID collision on subsequent inserts")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.users', 'id'), COALESCE((SELECT MAX(id) FROM public.users), 1));")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.projects', 'id'), COALESCE((SELECT MAX(id) FROM public.projects), 1));")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.stages', 'id'), COALESCE((SELECT MAX(id) FROM public.stages), 1));")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.tasks', 'id'), COALESCE((SELECT MAX(id) FROM public.tasks), 1));")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.assignees', 'id'), COALESCE((SELECT MAX(id) FROM public.assignees), 1));")
    sql_lines.append("SELECT setval(pg_get_serial_sequence('public.colors', 'id'), COALESCE((SELECT MAX(id) FROM public.colors), 1));")
    sql_lines.append("")

    with open('supabase_schema.sql', 'w', encoding='utf-8') as f:
        f.write("\n".join(sql_lines))

    print(f"Generated supabase_schema.sql successfully ({len(sql_lines)} lines)")

if __name__ == '__main__':
    main()
